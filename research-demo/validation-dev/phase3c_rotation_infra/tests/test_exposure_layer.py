"""Task 2 (part 1) / 7: the exposure layer is generated once per seed and
is identical regardless of how many times, or in what order, it is read
-- the property the counterfactual comparison across rotation policies
depends on (PHASE3B section 5a/5b)."""

from __future__ import annotations

import unittest
from pathlib import Path

from phase1_simulator import config as p1_config_mod
from phase3c_rotation_infra.exposure_layer import (
    generate_exposure_layer,
    generate_exposure_series,
    generate_room_boundaries,
    generate_slots_for_room,
)

P1_CONFIG_PATH = Path(p1_config_mod.__file__).parent / "config" / "simulation_config.json"


class TestExposureLayer(unittest.TestCase):
    def setUp(self):
        self.p1_cfg = p1_config_mod.load_config(P1_CONFIG_PATH)

    def test_boundaries_are_reproducible_and_span_the_shift(self):
        b1 = generate_room_boundaries(5, "Cath Lab 1", 180, _p3c())
        b2 = generate_room_boundaries(5, "Cath Lab 1", 180, _p3c())
        self.assertEqual(b1, b2)
        self.assertEqual(b1[0], 0)
        self.assertEqual(b1[-1], 180)
        self.assertEqual(b1, sorted(b1))

    def test_slots_partition_the_shift_without_gap_or_overlap(self):
        slots = generate_slots_for_room(5, "Cath Lab 1", 180, self.p1_cfg)
        self.assertEqual(slots[0].start_minute, 0)
        self.assertEqual(slots[-1].end_minute, 180)
        for a, b in zip(slots, slots[1:]):
            self.assertEqual(a.end_minute, b.start_minute)

    def test_exposure_series_identical_across_repeated_generation_same_seed(self):
        slots = generate_slots_for_room(11, "CT Suite", 120, self.p1_cfg)
        series_a = [generate_exposure_series(11, s) for s in slots]
        series_b = [generate_exposure_series(11, s) for s in slots]
        self.assertEqual(series_a, series_b)

    def test_exposure_series_same_across_different_rotation_policies(self):
        """The exposure layer must not depend on, or be regenerated by,
        whatever assignment/rotation policy later reads it. Simulated
        here by generating the layer twice with no knowledge of any
        assignment at all -- the exposure_layer module has no assignment
        parameter to pass, which is itself the guarantee (section 5a
        point 1: 'never regenerated per rotation policy')."""
        slots_by_room = {
            "Cath Lab 1": generate_slots_for_room(99, "Cath Lab 1", 150, self.p1_cfg),
            "CT Suite": generate_slots_for_room(99, "CT Suite", 150, self.p1_cfg),
        }
        layer_1 = generate_exposure_layer(99, slots_by_room)
        layer_2 = generate_exposure_layer(99, slots_by_room)
        self.assertEqual(layer_1, layer_2)

    def test_each_slot_series_has_correct_length(self):
        slots = generate_slots_for_room(3, "PET/CT Suite", 90, self.p1_cfg)
        for slot in slots:
            series = generate_exposure_series(3, slot)
            self.assertEqual(len(series), slot.end_minute - slot.start_minute)

    def test_baseline_reused_from_phase1_procedure_classes_not_invented(self):
        slots = generate_slots_for_room(3, "PET/CT Suite", 90, self.p1_cfg)
        classes = self.p1_cfg.procedure_classes()
        for slot in slots:
            proc_cfg = classes[slot.procedure_class]
            lo, hi = proc_cfg["proc_mult_range"]
            self.assertTrue(lo <= slot.proc_mult <= hi)
            self.assertAlmostEqual(slot.baseline_rate_uSv_h,
                                    proc_cfg["baseline_rate_uSv_h"] * slot.proc_mult)


def _p3c():
    from phase3c_rotation_infra.config import load_config
    return load_config()


if __name__ == "__main__":
    unittest.main()
